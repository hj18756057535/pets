// Injected only into the isolated debug smoke process; all data is synthetic.
window.addEventListener('DOMContentLoaded', () => setTimeout(async () => {
  const $ = id => document.getElementById(id), checks = [];
  const assert = (condition, message) => { if (!condition) throw new Error(message); checks.push(message); };
  const call = (channel, input = null) => window.__TAURI__.core.invoke('maskdesk_call', { channel, input });
  const click = async id => {
    $(id).click();
    const until = Date.now() + 15000;
    while ($('workspace').disabled && Date.now() < until) await new Promise(resolve => setTimeout(resolve, 40));
    if ($('workspace').disabled) throw new Error('UI operation timed out: ' + id);
    if ($('status').classList.contains('error')) throw new Error(id + ': ' + $('status').textContent);
  };
  const input = (el, value) => { el.value = value; el.dispatchEvent(new Event('input', { bubbles: true })); };
  const reversible = value => { $('reversible').checked = value; $('reversible').dispatchEvent(new Event('change', { bubbles: true })); };
  try {
    reversible(false);
    await click('load-example'); await click('preview-text');
    assert($('result-text').value === '公司 A的联系人 A负责新项目，请帮我整理会议纪要。', '中文关键词替换');
    input($('source-text'), '另一个输入');
    assert($('copy-text').disabled && !$('result-text').value, '文本变更使旧结果失效');
    await click('sheet-tab'); await click('open-file');
    assert($('sheet-select').options.length === 2, '读取多个工作表名称');
    const rows = [...$('column-rules').children];
    rows.forEach(row => { row.querySelector('input[type=checkbox]').checked = true; });
    input(rows[1].querySelector('.head'), 3); input(rows[1].querySelector('.tail'), 4);
    await click('preview-sheet');
    assert($('after-table').textContent.includes('张****明') && $('after-table').textContent.includes('138****5678'), '逐列保留不同首尾');
    assert($('sheet-count').textContent.includes('修改 2 个单元格'), '全表修改数量');
    input(rows[0].querySelector('.head'), 0);
    assert($('export-sheet').disabled, '规则变更禁用旧导出');
    input(rows[0].querySelector('.head'), 1); await click('preview-sheet');
    await click('export-sheet');
    assert($('status').textContent.includes('已导出'), '导出真实 XLSX 文件');
    await click('clear-session');
    assert($('file-workspace').hidden && !$('source-text').value && !$('result-text').value, '清空界面与输入');
    let rejected = false;
    try { await call('preview', { columns: [{ column: 0, rule: { mode: 'mask', head: 1, tail: 1 } }], header: true }); }
    catch { rejected = true; }
    assert(rejected, '清空后后端拒绝旧表格操作');
    reversible(true); await click('text-tab');
    const original = '联系人张小明，手机13812345678，邮箱user@example.com，证件11010519491231002X';
    input($('source-text'), original);
    input($('keyword-rules').querySelector('.find'), '张小明');
    await click('detect-text');
    assert($('text-candidates').children.length === 3 && $('keyword-rules').children.length === 1, '识别三类格式，确认前不更改规则');
    await click('apply-text-candidates');
    assert($('keyword-rules').children.length === 4, '审阅确认后添加关键词');
    await click('preview-text');
    const masked = $('result-text').value, mappingId = $('mapping-select').value;
    assert(masked.includes('[[PD_') && !/张小明|13812345678|user@example.com|11010519491231002X/.test(masked), '可恢复预览不含原始关键词');
    await click('restore-tab'); input($('ai-response'), 'AI 结论：' + masked);
    await click('restore-result');
    assert($('restored-text').value === 'AI 结论：' + original, 'AI 返回结果通过原映射还原');
    input($('ai-response'), masked + ' [[PD_unknown_0001]]'); await click('restore-result');
    assert($('restored-text').value.endsWith('[[PD_unknown_0001]]') && $('restore-count').textContent.includes('未识别占位符 1'), '未知占位符保持原样并提示');
    input($('mapping-password'), 'synthetic-smoke-password'); input($('mapping-password-confirm'), 'synthetic-smoke-password');
    await click('save-mapping');
    assert(!$('mapping-password').value && !$('mapping-password-confirm').value, '加密保存后清空密码输入');
    await click('sheet-tab'); await click('open-file');
    assert($('mapping-select').value === mappingId, '重新打开表格保留旧文本映射');
    await click('detect-sheet'); await click('apply-sheet-candidates');
    const phoneRow = $('column-rules').children[1];
    assert(phoneRow.querySelector('input[type=checkbox]').checked && phoneRow.querySelector('select').value === 'keywords', '表格候选确认后设置所在列');
    await click('preview-sheet');
    assert($('after-table').textContent.includes('[[PD_') && $('mapping-select').options.length === 2, '表格关键词生成独立可恢复映射');
    await click('restore-tab'); $('mapping-select').value = mappingId; $('mapping-select').dispatchEvent(new Event('change'));
    input($('ai-response'), masked); await click('restore-result');
    assert($('restored-text').value === original, '新预览不覆盖旧映射');
    await click('clear-session');
    assert($('clear-dialog').open, '清空前提示映射丢失'); await click('confirm-clear');
    assert(!$('mapping-select').value && !$('ai-response').value, '清空同时释放映射与还原数据');
    input($('mapping-password'), 'synthetic-smoke-password'); await click('load-mapping');
    input($('ai-response'), masked); await click('restore-result');
    assert($('restored-text').value === original, '清空后导入加密映射仍可还原');
    await click('text-tab');
    $('keyword-rules').replaceChildren();
    await click('add-keyword');
    input($('keyword-rules').querySelector('.find'), '星河科技有限公司');
    input($('keyword-rules').querySelector('.replace'), '公司 A');
    input($('rule-group-name'), '项目 A'); await click('save-rule-group');
    assert((await call('rule-groups'))[0].rules[0].replace === '公司 A', '可恢复模式保存规则仍保留普通替换值');
    await click('clear-session'); await click('confirm-clear');
    $('rule-group-select').value = '项目 A'; await click('load-rule-group');
    assert($('keyword-rules').querySelector('.find').value === '星河科技有限公司', '清空会话后规则库仍可复用');
    input($('keyword-rules').querySelector('.replace'), '企业 A'); await click('update-rule-group');
    assert((await call('rule-groups'))[0].rules[0].replace === '企业 A', '显式更新所选规则组');
    await click('open-document');
    assert($('document-name').textContent === '测试合同.docx' && $('source-text').value.includes('星河科技'), 'Word 文件提取文字');
    await click('preview-text');
    const documentMasked = $('result-text').value;
    await click('export-text');
    assert($('status').textContent.includes('测试合同_脱敏_') && $('status').textContent.includes('.docx'), 'Word 以原文件名和时间导出');
    $('text-export-format').value = 'txt'; await click('export-text');
    assert($('status').textContent.includes('.txt'), '同一预览可导出 UTF-8 TXT');
    await click('restore-tab'); input($('ai-response'), documentMasked); await click('restore-result');
    assert($('restored-text').value.includes('星河科技有限公司'), 'Word 脱敏结果可通过映射还原');
    await click('text-tab'); input($('source-text'), '新的内容');
    assert($('export-text').disabled, '编辑原文使文档导出预览失效');
    const txt = await call('open-document', 'txt');
    assert(txt.name.endsWith('.txt') && txt.text.includes('星河科技'), 'TXT 文件导入通道');
    await call('smoke-report', { ok: true, checks });
  } catch (error) { await call('smoke-report', { ok: false, checks, error: error.message }); }
}, 200));
